export type Copy = { [K in keyof (typeof copy)["en"]]: string };

const Ctx = createContext<{ lang: LangId; setLang: (id: LangId) => void; t: Copy }>({
  lang: "en",
  setLang: () => undefined,
  t: copy.en,
});

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangId>("en");
  useEffect(() => {
    const saved = window.localStorage.getItem("tillsnap-lang");
    if (saved && saved in copy) setLangState(saved as LangId);
  }, []);
  const setLang = (id: LangId) => {
    setLangState(id);
    window.localStorage.setItem("tillsnap-lang", id);
    document.documentElement.lang = id;
    document.documentElement.dir = id === "ur" ? "rtl" : "ltr";
  };
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ur" ? "rtl" : "ltr";
  }, [lang]);
  return <Ctx.Provider value={{ lang, setLang, t: { ...copy.en, ...copy[lang] } }}>{children}</Ctx.Provider>;
}

export function useI18n() {
  return useContext(Ctx);
}
